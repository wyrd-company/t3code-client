// ---
// relationships:
//   implements: command-line
//   references: library, releasing
// ---
import * as NodeFSP from "node:fs/promises";
import * as NodePath from "node:path";

const root = NodePath.resolve(import.meta.dirname, "..");
const repository = NodePath.resolve(root, "../..");
const pages = [
  ["docs/command-contract.md", "commands.md", "Command behavior", 3],
  ["docs/output-contract.md", "policy.md", "Output, exits and requests", 4],
  ["docs/harness.md", "dagu.md", "Dagu harness", 5],
  ["../t3code-lib/docs/api.md", "library.md", "Library API", 6],
];
for (const [source, destination, title, order] of pages) {
  const path = NodePath.resolve(root, source);
  const content = await NodeFSP.readFile(path, "utf8");
  let body = content.replace(/^---\n[\s\S]*?\n---\n/, "");
  body = body.replace(/\]\(([^)]+)\)/gu, (match, href) => {
    if (/^(?:[a-z]+:|#)/u.test(href)) return match;
    const mapped = pages.find(
      ([candidate]) =>
        NodePath.resolve(root, candidate) === NodePath.resolve(NodePath.dirname(path), href),
    );
    if (mapped) return `](${mapped[1]})`;
    const target = NodePath.relative(repository, NodePath.resolve(NodePath.dirname(path), href));
    return `](https://github.com/wyrd-company/t3code-client/blob/main/${target})`;
  });
  const output = `---\ndocs: true\ntitle: ${title}\norder: ${order}\nrelationships:\n  references: [command-line, library, releasing]\n---\n\n<!-- Generated by task cli:docs from ${source}; edit the source. -->\n${body}`;
  const target = NodePath.join(root, "docs", destination);
  if (process.argv.includes("--check")) {
    if ((await NodeFSP.readFile(target, "utf8")) !== output)
      throw new Error(`Regenerate ${destination} with task cli:docs.`);
  } else await NodeFSP.writeFile(target, output);
}
