// ---
// relationships:
//   implements: documentation
//   references: command-line, library, releasing
// ---
import * as NodeFSP from "node:fs/promises";
import * as NodePath from "node:path";

const repository = NodePath.resolve(import.meta.dirname, "../../..");
const root = NodePath.join(repository, "docs");
const pages = [
  ["specifications/assets/command-contract.json", "commands.md", "Command behavior", 3],
  ["specifications/assets/output-contract.json", "policy.md", "Output, exits and requests", 4],
  ["specifications/assets/harness.json", "dagu.md", "Dagu harness", 5],
  ["api.md", "library.md", "Library API", 6],
];
for (const [source, destination, title, order] of pages) {
  const path = NodePath.join(root, source);
  const content = await NodeFSP.readFile(path, "utf8");
  let body;
  if (source.endsWith(".json")) {
    const contract = JSON.parse(content);
    if (
      typeof contract.title !== "string" ||
      !Array.isArray(contract.sections) ||
      contract.sections.length === 0 ||
      contract.sections.some(
        (section) => typeof section.title !== "string" || typeof section.body !== "string",
      )
    )
      throw new Error(`Invalid semantic sections in ${source}.`);
    body = `\n# ${contract.title}\n\n${contract.sections
      .map(({ title, body }) => `${title === "Overview" ? "" : `## ${title}\n\n`}${body}\n`)
      .join("\n")}`;
  } else body = content.replace(/^---\n[\s\S]*?\n---\n/, "");
  body = body.replace(/\]\(([^)]+)\)/gu, (match, href) => {
    if (/^(?:[a-z]+:|#)/u.test(href)) return match;
    const [link, anchor] = href.split("#");
    const resolved = NodePath.resolve(NodePath.dirname(path), link);
    const mapped = pages.find(([candidate]) => NodePath.join(root, candidate) === resolved);
    // Published projections link to each other; other references resolve to
    // the canonical artifact in the source repository.
    const target = mapped
      ? mapped[1]
      : `https://github.com/wyrd-company/t3code-client/blob/main/${NodePath.relative(repository, resolved)}`;
    return `](${target}${anchor === undefined ? "" : `#${anchor}`})`;
  });
  const output = `---\ndocs: true\ntitle: ${title}\norder: ${order}\nrelationships:\n  references: [command-line, library, releasing]\n---\n\n<!-- Generated by task cli:docs from docs/${source}; edit the source. -->\n${body}`;
  const target = NodePath.join(root, destination);
  if (process.argv.includes("--check")) {
    if ((await NodeFSP.readFile(target, "utf8")) !== output)
      throw new Error(`Regenerate ${destination} with task cli:docs.`);
  } else await NodeFSP.writeFile(target, output);
}
