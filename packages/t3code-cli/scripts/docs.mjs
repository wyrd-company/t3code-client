// ---
// relationships:
//   implements: documentation
//   references: library, library-reference
// ---
import * as NodeFSP from "node:fs/promises";
import * as NodePath from "node:path";

const repository = NodePath.resolve(import.meta.dirname, "../../..");
const root = NodePath.join(repository, "docs");
const source = "api.md";
const destination = "library-reference.md";
const content = await NodeFSP.readFile(NodePath.join(root, source), "utf8");
const body = content
  .replace(/^---\n[\s\S]*?\n---\n/u, "")
  .replace(/\]\(([^)]+)\)/gu, (match, href) => {
    if (/^(?:[a-z]+:|#)/u.test(href)) return match;
    const [link, anchor] = href.split("#");
    const target = NodePath.resolve(root, link);
    const mapped =
      target === NodePath.join(root, source)
        ? destination
        : `https://github.com/wyrd-company/t3code-client/blob/main/${NodePath.relative(repository, target)}`;
    return `](${mapped}${anchor === undefined ? "" : `#${anchor}`})`;
  });
const output = `---\ndocs: true\ntitle: Library API\norder: 6\nrelationships:\n  references: [library, api]\n---\n\n<!-- Generated by task cli:docs from docs/api.md; edit the source. -->\n${body}`;
const target = NodePath.join(root, destination);
if (process.argv.includes("--check")) {
  if ((await NodeFSP.readFile(target, "utf8")) !== output)
    throw new Error(`Regenerate ${destination} with task cli:docs.`);
} else await NodeFSP.writeFile(target, output);
