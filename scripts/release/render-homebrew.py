"""Render t3c from actual npm pack bytes; never supply a checksum by hand."""
import argparse
import hashlib
import json
import re
import tarfile
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("archive", type=Path)
parser.add_argument("url")
parser.add_argument("output", type=Path)
parser.add_argument("--local-library", type=Path, help="Local validation only: install matching packed library")
args = parser.parse_args()
with tarfile.open(args.archive) as archive:
    manifest = json.load(archive.extractfile("package/package.json"))
if manifest.get("name") != "@wyrd-company/t3code-cli" or manifest.get("private"):
    parser.error("expected public @wyrd-company/t3code-cli package")
version = manifest["version"]
if not re.fullmatch(r"\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?", version):
    parser.error("invalid package version")
expected = f"https://registry.npmjs.org/@wyrd-company/t3code-cli/-/t3code-cli-{version}.tgz"
if args.local_library:
    if args.url != args.archive.resolve().as_uri():
        parser.error("local validation requires the exact archive file URL")
elif args.url != expected:
    parser.error(f"expected npm tarball URL {expected}")
digest = hashlib.sha256(args.archive.read_bytes()).hexdigest()
comment = "# Generated by scripts/release/render-homebrew.py; do not edit.\n"
if version == "0.0.0":
    comment += "# Provisional local pack: epic branch only; regenerate from published npm bytes before tap main.\n"
local = f",\n           {json.dumps(str(args.local_library.resolve()))}" if args.local_library else ""
args.output.parent.mkdir(parents=True, exist_ok=True)
args.output.write_text(comment + f'''# relationships:
#   implements: releasing
class T3c < Formula
  desc "Run T3 Code conversations from the terminal and automation"
  homepage "https://github.com/wyrd-company/t3code-client"
  url {json.dumps(args.url)}
  sha256 "{digest}"
  license "MIT"

  depends_on "node"

  def install
    system "npm", "install", *std_npm_args{local}
    bin.install_symlink Dir["#{{libexec}}/bin/*"]
  end

  test do
    assert_match "t3c #{{version}}", shell_output("#{{bin}}/t3c --version")
  end
end
''')
